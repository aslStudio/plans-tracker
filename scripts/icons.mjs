import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

import { format } from 'prettier'

const args = Object.fromEntries(
    process.argv.slice(2).map((a) => {
        const [k, v] = a.split('=')
        return [k.replace(/^--/, ''), v ?? true]
    }),
)

const ROOT = String('assets/icons')
const DRY = Boolean(args.dry)
const KEEP_SIZE = Boolean(args.keepSize)

const MONO_DIR = path.join(ROOT, 'mono')
const MULTI_DIR = path.join(ROOT, 'multi')

const MODEL_PATH = path.join('src/shared/config', 'icons.ts')

function toPascalCase(str) {
    return str
        .replace(/[^a-zA-Z0-9]+/g, ' ')
        .trim()
        .split(/\s+/)
        .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
        .join('')
}

function toIconKey(str) {
    return str.toLowerCase()
}

function normalizeMonoSvg(svg, { keepSize }) {
    let out = svg

    out = out.replace(/\sfill=(["'])(?!none\b)([^"']+)\1/gi, (m, q, val) => {
        if (/^url\(/i.test(val.trim())) return m
        return ` fill=${q}currentColor${q}`
    })

    out = out.replace(/\sstroke=(["'])(?!none\b)([^"']+)\1/gi, (m, q, val) => {
        if (/^url\(/i.test(val.trim())) return m
        return ` stroke=${q}currentColor${q}`
    })

    if (!keepSize) {
        out = out.replace(/<svg\b([^>]*)>/i, (m, attrs) => {
            let a = attrs
            a = a.replace(/\s(width|height)=(["'])(.*?)\2/gi, '')
            return `<svg${a}>`
        })
    }

    return out
}

async function listSvgFiles(dir) {
    try {
        const items = await readdir(dir, { withFileTypes: true })
        return items
            .filter((d) => d.isFile() && d.name.endsWith('.svg'))
            .map((d) => d.name)
            .sort()
    } catch {
        return []
    }
}

async function ensureDirs() {
    await mkdir(MONO_DIR, { recursive: true })
    await mkdir(MULTI_DIR, { recursive: true })
}

async function normalizeMonoFolder() {
    const files = await listSvgFiles(MONO_DIR)

    for (const file of files) {
        const p = path.join(MONO_DIR, file)
        const raw = await readFile(p, 'utf8')
        const next = normalizeMonoSvg(raw, { keepSize: KEEP_SIZE })

        if (raw !== next) {
            if (!DRY) await writeFile(p, next, 'utf8')
            console.log(`mono: normalized ${file}${DRY ? ' (dry)' : ''}`)
        }
    }
}

function buildConfigTs({ mono, multi }) {
    const monoData = mono.map((file) => {
        const base = file.replace('.svg', '')
        return {
            key: toIconKey(base),
            comp: toPascalCase(base),
            rel: `../../../assets/icons/mono/${file}`,
        }
    })

    const multiData = multi.map((file) => {
        const base = file.replace('.svg', '')
        return {
            key: toIconKey(base),
            comp: toPascalCase(base),
            rel: `../../../assets/icons/multi/${file}`,
        }
    })

    const imports = [
        `import type { ComponentType } from "react";`,
        `import type { SvgProps } from "react-native-svg";`,
        '',
        ...monoData.map((x) => `import ${x.comp} from "${x.rel}";`),
        ...(monoData.length && multiData.length ? [''] : []),
        ...multiData.map((x) => `import ${x.comp} from "${x.rel}";`),
        '',
    ].join('\n')

    const monoObj = `export const monoIcons = {
${monoData.map((x) => `  '${x.key}': ${x.comp},`).join('\n')}
} satisfies Record<string, ComponentType<SvgProps>>;`

    const multiObj = `export const multiIcons = {
${multiData.map((x) => `  '${x.key}': ${x.comp},`).join('\n')}
} satisfies Record<string, ComponentType<SvgProps>>;`

    return `// AUTO-GENERATED FILE. DO NOT EDIT.
// Generated by scripts/icons.mjs

${imports}

${monoObj}

${multiObj}

export type MonoIconName = keyof typeof monoIcons;
export type MultiIconName = keyof typeof multiIcons;
export type IconName = MonoIconName | MultiIconName;
export const icons = [...Object.keys(monoIcons), ...Object.keys(multiIcons)] as IconName[] ;
`
}

async function generateModel() {
    const mono = await listSvgFiles(MONO_DIR)
    const multi = await listSvgFiles(MULTI_DIR)

    const content = await format(buildConfigTs({ mono, multi }), {
        parser: 'typescript',
        tabWidth: 4,
        semi: false,
        singleQuote: true,
        trailingComma: 'all',
        printWidth: 100,
    })

    if (!DRY) {
        await writeFile(MODEL_PATH, content, 'utf8')
    }

    console.log(
        `config: regenerated ${path.relative(process.cwd(), MODEL_PATH)}${DRY ? ' (dry)' : ''}`,
    )
}

async function main() {
    await ensureDirs()
    await normalizeMonoFolder()
    await generateModel()
}

main().catch((e) => {
    console.error(e)
    process.exit(1)
})
