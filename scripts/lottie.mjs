import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import { format, resolveConfig } from 'prettier'

const projectRoot = fileURLToPath(new URL('../', import.meta.url))
const assetRoot = path.join(projectRoot, 'assets/lottie')
const outputPath = path.join(projectRoot, 'src/shared/config/lottie.ts')
const check = process.argv.includes('--check')

async function generate() {
    const imports = []

    async function visit(directory) {
        const entries = (
            await readdir(directory, { withFileTypes: true })
        ).sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
        const properties = new Map()

        for (const entry of entries) {
            const fullPath = path.join(directory, entry.name)
            let key
            let value
            if (entry.isDirectory()) {
                value = await visit(fullPath)
                if (!value) continue
                key = entry.name
            } else if (entry.isFile() && entry.name.endsWith('.tgs')) {
                key = entry.name.slice(0, -4)
                value = `lottieAsset${imports.length}`
                const relativePath = path
                    .relative(path.dirname(outputPath), fullPath)
                    .split(path.sep)
                    .join('/')
                imports.push(
                    `import ${value} from ${JSON.stringify(relativePath)}`,
                )
            } else {
                continue
            }

            if (properties.has(key)) {
                throw new Error(
                    `Duplicate lottie key ${JSON.stringify(key)} in ${directory}`,
                )
            }
            properties.set(key, value)
        }

        if (!properties.size) return null
        return `{
            ${[...properties]
                .map(([key, value]) => {
                    const property =
                        key === '__proto__'
                            ? `[${JSON.stringify(key)}]`
                            : JSON.stringify(key)
                    return `${property}: ${value},`
                })
                .join('\n')}
        }`
    }

    const tree = (await visit(assetRoot)) ?? '{}'
    const source = await format(
        `// AUTO-GENERATED by scripts/lottie.mjs. Do not edit manually.
        // Run npm run lottie:generate after changing assets/lottie.
        // Keys mirror directory and file names exactly, without the .tgs extension.

        ${imports.join('\n')}

        export const lottie = ${tree} as const
        `,
        { ...(await resolveConfig(outputPath)), filepath: outputPath },
    )

    if (check) {
        const current = await readFile(outputPath, 'utf8').catch((error) => {
            if (error.code === 'ENOENT') return null
            throw error
        })
        if (current !== source) {
            throw new Error(
                'Lottie registry is outdated. Run npm run lottie:generate.',
            )
        }
        console.log(`Lottie registry is up to date (${imports.length} assets).`)
        return
    }

    await mkdir(path.dirname(outputPath), { recursive: true })
    await writeFile(outputPath, source, 'utf8')
    console.log(
        `Generated src/shared/config/lottie.ts (${imports.length} assets).`,
    )
}

generate().catch((error) => {
    console.error(error.message)
    process.exitCode = 1
})
